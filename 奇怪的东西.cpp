/*
给出正整数 n，要求按如下方式构造数列：
1.只有一个数 n 的数列是一个合法的数列。
2.在一个合法的数列的末尾加入一个正整数，但是这个正整数不能超过该数列最后一项的一半，可以得到一个新的合法数列。
请你求出，一共有多少个合法的数列。两个合法数列 a,b 不同当且仅当两数列长度不同或存在一个正整数 i ≤ |a|，使得 a_i≠b_i。
*/
#include<stdio.h>
int arr[1005];
int main() {
	int n, x, i;
	int temp;
	scanf("%d", &n);
	arr[1] = 1;
	for (int i = 2; i <= n; i++) {
		arr[i] = 1;
		x = i / 2;
		for (int j = 1; j <= x; j++) {
			arr[i] = arr[i] + arr[j] ;
		}
	}
	printf("%d", arr[n]);
	return 0;
}


